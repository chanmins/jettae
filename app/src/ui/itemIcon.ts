/**
 * 이름 규칙만으로 찾은 그림. 안 걸리면 null.
 * 커버리지를 재는 쪽에서 "구역으로 떨어졌는지"를 구분하려고 따로 내보낸다 —
 * 침구가 🛏️를 받은 것과 침실 기본값이 🛏️인 것은 결과가 같아도 다른 일이다.
 */
export function iconByName(name: string): string | null {
  for (const [re, emoji] of NAME_TABLE) if (re.test(name)) return emoji;
  return null;
}

/** 품목 그림. 등록된 품목(Item)과 카탈로그 품목(CatalogItem) 모두에 쓴다. */
export function itemIcon(item: { name: string; zone: Zone }): string {
  return iconByName(item.name) ?? ZONE_ICON[item.zone];
}
